# 数据类型转换
'''
在编程时常用的数据类型转换
int(x[,base]) 将x转换为一个整数，base为进制数
float(x) 将x转化为浮点数
complex(real[,image]) 创建一个复数，real表示实部，image表示虚部
str(x) 将x转化为字符串
repr(x) 将x转化为表达式字符串
tuple(s) 将s转化为一个元组
list(s) 将s转化为一个列表
set(s) 将s转化为一个集合
dict(d) 将s转化为一个可变集合(自动去重)
frozenset(s) 将s转化为一个锁定集合(不可变)
chr(x) 将一个整数转化为一个字符
ord(x)_ 将一个字符转化为它的整数值
hex(x) 将整数转化为一个十六进制字符串
oct(x) 将整数转化为一个八进制字符串
bin(x) 将整数转化为一个二进制字符串
eval(str) 计算字符串中的有效表达式，并返回一个对象
'''
